// Package contractbundle merges a contract and the files it references into one
// document, so app developers get one file and generated code gets clean names.
package contractbundle

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// Header is written at the top of every bundled file.
const Header = "# Generated by `task contracts:bundle`. Do not edit. Change the files in contracts/customer, contracts/rider, contracts/partner, contracts/console or contracts/shared.\n"

type bundler struct {
	root     map[string]any
	rootPath string
	docs     map[string]map[string]any
	origin   map[string]string
}

// Bundle returns the YAML for the contract at path, with every external reference brought in.
func Bundle(path string) ([]byte, error) {
	root, err := load(path)
	if err != nil {
		return nil, err
	}
	b := &bundler{root: root, rootPath: filepath.Clean(path), docs: map[string]map[string]any{filepath.Clean(path): root}, origin: map[string]string{}}
	if components, ok := root["components"].(map[string]any); ok {
		for kind, entries := range components {
			if m, ok := entries.(map[string]any); ok {
				for name := range m {
					b.origin[kind+"/"+name] = b.rootPath
				}
			}
		}
	}
	if err := b.rewrite(root, b.rootPath); err != nil {
		return nil, err
	}
	out, err := yaml.Marshal(root)
	if err != nil {
		return nil, err
	}
	return append([]byte(Header), out...), nil
}

func load(path string) (map[string]any, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc map[string]any
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return doc, nil
}

func (b *bundler) rewrite(node any, current string) error {
	switch v := node.(type) {
	case []any:
		for _, item := range v {
			if err := b.rewrite(item, current); err != nil {
				return err
			}
		}
	case map[string]any:
		if ref, ok := v["$ref"].(string); ok {
			local, err := b.bringIn(ref, current)
			if err != nil {
				return err
			}
			v["$ref"] = local
			return nil
		}
		for _, child := range v {
			if err := b.rewrite(child, current); err != nil {
				return err
			}
		}
	}
	return nil
}

// bringIn copies the referenced component into the root document, and returns the local reference.
func (b *bundler) bringIn(ref, current string) (string, error) {
	file, pointer, found := strings.Cut(ref, "#")
	if !found {
		return "", fmt.Errorf("%s: reference %q has no pointer", current, ref)
	}
	target := current
	if file != "" {
		target = filepath.Clean(filepath.Join(filepath.Dir(current), file))
	}
	if target == b.rootPath {
		return "#" + pointer, nil
	}
	parts := strings.Split(strings.TrimPrefix(pointer, "/"), "/")
	if len(parts) != 3 || parts[0] != "components" {
		return "", fmt.Errorf("%s: cannot bundle %q: only components can be shared", current, ref)
	}
	kind, name := parts[1], parts[2]
	local := "#/components/" + kind + "/" + name
	key := kind + "/" + name
	if from, seen := b.origin[key]; seen {
		if from != target {
			return "", fmt.Errorf("%s/%s is defined in both %s and %s", kind, name, from, target)
		}
		return local, nil
	}
	doc, ok := b.docs[target]
	if !ok {
		var err error
		if doc, err = load(target); err != nil {
			return "", err
		}
		b.docs[target] = doc
	}
	components, _ := doc["components"].(map[string]any)
	entries, _ := components[kind].(map[string]any)
	entry, ok := entries[name]
	if !ok {
		return "", fmt.Errorf("%s: %q does not exist", current, ref)
	}
	b.origin[key] = target
	rootComponents, _ := b.root["components"].(map[string]any)
	if rootComponents == nil {
		rootComponents = map[string]any{}
		b.root["components"] = rootComponents
	}
	rootEntries, _ := rootComponents[kind].(map[string]any)
	if rootEntries == nil {
		rootEntries = map[string]any{}
		rootComponents[kind] = rootEntries
	}
	rootEntries[name] = entry
	if err := b.rewrite(entry, target); err != nil {
		return "", err
	}
	return local, nil
}

// Files lists each source contract and its bundled name.
var Files = map[string]string{
	"customer/openapi.yaml":         "customer.openapi.yaml",
	"customer/stream.asyncapi.yaml": "customer.stream.asyncapi.yaml",
	"rider/openapi.yaml":            "rider.openapi.yaml",
	"rider/stream.asyncapi.yaml":    "rider.stream.asyncapi.yaml",
	"partner/openapi.yaml":          "partner.openapi.yaml",
	"partner/stream.asyncapi.yaml":  "partner.stream.asyncapi.yaml",
	"console/openapi.yaml":          "console.openapi.yaml",
}

// All bundles every contract under dir, and returns the output by file name.
func All(dir string) (map[string][]byte, error) {
	out := map[string][]byte{}
	for src, name := range Files {
		data, err := Bundle(filepath.Join(dir, filepath.FromSlash(src)))
		if err != nil {
			return nil, err
		}
		out[name] = data
	}
	return out, nil
}
